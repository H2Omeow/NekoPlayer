#!/usr/bin/env python3
"""Validate i18n/catalog.json and generate per-platform string tables."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "i18n" / "catalog.json"
GLOSSARY = ROOT / "i18n" / "glossary.json"
WEB = Path("/www/wwwroot/superplayer")
LANGS = ("zh-TW", "en", "ja")
PLACEHOLDER = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")
CJK = re.compile(r"[㐀-鿿]")
# Proper names and user-facing strings where Chinese is intentional.
CJK_ALLOWLIST = {
    "NekoPlayer",
    "超级播放器",
    "简体中文",
    "繁體中文",
    "日本語",
}


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def placeholders(value: str) -> set[str]:
    return set(PLACEHOLDER.findall(value))


def variants(value: object) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, dict):
        return [text for text in value.values() if isinstance(text, str)]
    return []


def validate(messages: dict[str, dict]) -> list[str]:
    errors: list[str] = []
    for source, entry in messages.items():
        if not isinstance(entry, dict):
            errors.append(f"{source!r}: entry must be an object")
            continue
        expected = placeholders(source)
        for lang in LANGS:
            if lang not in entry:
                errors.append(f"{source!r}: missing {lang}")
                continue
            values = variants(entry[lang])
            if not values:
                errors.append(f"{source!r}: {lang} must be a string or plural object")
                continue
            for value in values:
                missing = expected - placeholders(value)
                extra = placeholders(value) - expected
                if missing or extra:
                    errors.append(
                        f"{source!r}: {lang} placeholders differ (missing={sorted(missing)}, extra={sorted(extra)})"
                    )
            if lang == "en":
                for value in values:
                    if CJK.search(value) and value not in CJK_ALLOWLIST:
                        errors.append(f"{source!r}: {lang} still contains Chinese: {value!r}")
            if isinstance(entry[lang], dict) and "other" not in entry[lang]:
                errors.append(f"{source!r}: {lang} plural object needs 'other'")
    return errors


def table_for(messages: dict[str, dict], lang: str) -> dict[str, object]:
    table: dict[str, object] = {}
    for source, entry in messages.items():
        value = entry.get(lang)
        if isinstance(value, str):
            table[source] = value
        elif isinstance(value, dict):
            table[source] = value
    return table


def dart_table(name: str, table: dict[str, object]) -> str:
    body = json.dumps(table, ensure_ascii=False, indent=2, sort_keys=True)
    return (
        "// Generated by tools/i18n/build.py. DO NOT EDIT.\n"
        f"const Map<String, Object> {name} = {body};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--web", type=Path, default=WEB)
    args = parser.parse_args()

    if not CATALOG.exists():
        print(f"missing {CATALOG}", file=sys.stderr)
        return 1
    messages = load_json(CATALOG).get("messages", {})
    errors = validate(messages)
    if errors:
        for error in errors[:100]:
            print(error, file=sys.stderr)
        print(f"{len(errors)} validation error(s)", file=sys.stderr)
        return 1

    outputs: dict[Path, str] = {}
    for lang in LANGS:
        table = table_for(messages, lang)
        outputs[ROOT / "app/src/main/assets/i18n" / f"{lang}.json"] = (
            json.dumps(table, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        )
        outputs[args.web / "i18n" / f"{lang}.json"] = (
            json.dumps(table, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        )
        outputs[ROOT / "deploy/i18n" / f"{lang}.json"] = (
            json.dumps(table, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        )
    outputs[ROOT / "desktop_flutter/lib/i18n/string_tables.g.dart"] = (
        "// Generated by tools/i18n/build.py. DO NOT EDIT.\n"
        "// ignore_for_file: prefer_single_quotes\n\n"
        + dart_table("stringsZhTw", table_for(messages, "zh-TW"))
        + "\n"
        + dart_table("stringsEn", table_for(messages, "en"))
        + "\n"
        + dart_table("stringsJa", table_for(messages, "ja"))
    )

    changed: list[Path] = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            changed.append(path)
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if changed:
        for path in changed:
            print(("generated " if args.write else "out of date ") + str(path))
        if args.check and not args.write:
            return 1
    print(f"catalog valid: {len(messages)} messages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
